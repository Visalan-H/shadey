// Unknown characters render as a blank so typing never throws or drops a gap.
export function glyphFor(ch: string): readonly string[] {
    return GLYPHS[ch.toUpperCase()] ?? GLYPHS[' ']!;
}

// Text -> 5-row bitmap, glyphs separated by one blank column. A space glyph is
// one column wide, so a word break comes out as three blank columns.
export function renderText(text: string): boolean[][] {
    const rows: boolean[][] = Array.from({ length: GLYPH_HEIGHT }, () => []);
    const chars = Array.from(text.toUpperCase());

    chars.forEach((ch, i) => {
        const glyph = glyphFor(ch);
        rows.forEach((row, r) => {
            for (const bit of glyph[r] ?? '') row.push(bit === '1');
            if (i < chars.length - 1) row.push(false);
        });
    });

    return rows;
}
